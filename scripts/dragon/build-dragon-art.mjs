#!/usr/bin/env node
/**
 * Builds src/components/ui/dragon-art.ts from the drawing script.
 *
 * The drawing script paints 142 facets in a fixed order. This groups them
 * into named body parts (the rig) WITHOUT reordering anything: each group
 * covers a run of consecutive facets, so painting the rig depth-first gives
 * exactly the original order. A part may appear more than once (the jaw is
 * split by the upper teeth, which are painted between its pieces); every
 * copy shares the part's pivot and moves together.
 *
 *   node scripts/dragon/build-dragon-art.mjs          write the file
 *   node scripts/dragon/build-dragon-art.mjs --check  fail if it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { polygons, sections } from "./draw-dragon.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const target = join(root, "src/components/ui/dragon-art.ts");

/**
 * Body parts. Pivots are in the drawing's own coordinates (the box
 * "20 0 172 220"): the joint each part naturally turns about.
 */
const parts = {
  wing: { label: "Wing (membrane and bones)", pivot: [103, 74], attachedTo: "torso", note: "Root of the wing at the shoulder; the wing is behind the body." },
  tail: { label: "Tail", pivot: [126, 146], attachedTo: "torso", note: "Base of the tail at the hip." },
  tailTip: { label: "Spade tip of the tail", pivot: [176, 98], attachedTo: "tail", note: "Where the tip meets the end of the tail." },
  farHindLeg: { label: "Far hind leg (raised) with claws", pivot: [127, 133], attachedTo: "torso", note: "Hip, top of the thigh." },
  torso: { label: "Body, belly and belly plates", pivot: [108, 110], attachedTo: null, note: "Middle of the body." },
  neck: { label: "Neck and back spines", pivot: [91, 79], attachedTo: "torso", note: "Base of the neck." },
  nearHindLeg: { label: "Near hind leg (planted) with claws", pivot: [110, 133], attachedTo: "torso", note: "Hip, top of the thigh." },
  lowerForeleg: { label: "Lower foreleg with claws", pivot: [92, 109], attachedTo: "torso", note: "Shoulder." },
  upperForeleg: { label: "Raised foreleg with claws", pivot: [89, 87], attachedTo: "torso", note: "Shoulder." },
  head: { label: "Head: horns, frill, skull, upper teeth, eye, brow, nostril", pivot: [80, 44], attachedTo: "neck", note: "Top of the neck." },
  jaw: { label: "Lower jaw, lower teeth and tongue", pivot: [77, 55], attachedTo: "head", note: "Jaw hinge at the back of the mouth." },
};

/**
 * The rig, in painting order. Strings are section names from the drawing
 * script (their facets are inlined); objects are groups.
 */
const rig = [
  { part: "wing", children: ["wing", "wingBones"] },
  { part: "tail", children: ["tail", { part: "tailTip", children: ["tailTip"] }] },
  { part: "farHindLeg", children: ["farHindLeg"] },
  { part: "torso", children: ["torso"] },
  { part: "neck", children: ["neck"] },
  { part: "nearHindLeg", children: ["nearHindLeg"] },
  { part: "lowerForeleg", children: ["lowerForeleg"] },
  { part: "upperForeleg", children: ["upperForeleg"] },
  {
    part: "head",
    children: [
      "horns",
      "skull",
      { part: "jaw", children: ["jaw"] },
      "upperTeeth",
      { part: "jaw", children: ["lowerTeeth", "tongue"] },
      "face",
    ],
  },
];

// Facet ranges per section.
const ranges = new Map();
for (let i = 0; i < sections.length - 1; i++) ranges.set(sections[i][0], [sections[i][1], sections[i + 1][1]]);

// Expand the rig and check it uses every facet exactly once, in order.
let next = 0;
function expand(node) {
  if (typeof node === "string") {
    const [from, to] = ranges.get(node) ?? [];
    if (from === undefined) throw new Error(`Unknown section ${node}`);
    if (from !== next) throw new Error(`Section ${node} starts at ${from}, expected ${next}: the rig would reorder facets`);
    next = to;
    return polygons.slice(from, to).map(([fill, points]) => ({ fill, points }));
  }
  if (!parts[node.part]) throw new Error(`Unknown part ${node.part}`);
  return [{ part: node.part, children: node.children.flatMap(expand) }];
}
const expanded = rig.flatMap(expand);
if (next !== polygons.length) throw new Error(`The rig covers ${next} of ${polygons.length} facets`);

// Write TypeScript.
const ind = (n) => "  ".repeat(n);
function emit(node, depth) {
  if (!node.part) return `${ind(depth)}["${node.fill}", "${node.points}"],`;
  return [
    `${ind(depth)}{`,
    `${ind(depth + 1)}part: "${node.part}",`,
    `${ind(depth + 1)}children: [`,
    ...node.children.map((c) => emit(c, depth + 2)),
    `${ind(depth + 1)}],`,
    `${ind(depth)}},`,
  ].join("\n");
}
const partIds = Object.keys(parts);
const out = `// GENERATED by scripts/dragon/build-dragon-art.mjs from scripts/dragon/draw-dragon.mjs.
// Do not edit by hand: change the drawing script and run the build script.

/**
 * The Zagoker dragon: an original low-poly dragon "rampant" (rearing on its
 * hind legs, claws raised, tail curling up behind), facing left, drawn in the
 * box \`20 0 172 220\`.
 *
 * The 142 facets are grouped into a rig of named body parts. Painting the rig
 * depth-first gives the facets in their original order, so the dragon looks
 * exactly as drawn. A part can appear more than once (the jaw is split by the
 * upper teeth, which are painted between its pieces); every copy shares the
 * part's pivot and must be moved together.
 */
export const dragonViewBox = "20 0 172 220";

/** One facet: [fill colour, SVG polygon points]. */
export type DragonFacet = readonly [fill: string, points: string];

export type DragonPartId = ${partIds.map((p) => `"${p}"`).join(" | ")};

export type DragonGroup = {
  readonly part: DragonPartId;
  readonly children: readonly (DragonFacet | DragonGroup)[];
};

export type DragonPartInfo = {
  readonly label: string;
  /** The joint the part turns about, in drawing coordinates. */
  readonly pivot: readonly [x: number, y: number];
  /** The part it hangs from; moving that part should carry this one. */
  readonly attachedTo: DragonPartId | null;
  readonly note: string;
};

export const dragonParts: Readonly<Record<DragonPartId, DragonPartInfo>> = {
${partIds.map((id) => `  ${id}: { label: ${JSON.stringify(parts[id].label)}, pivot: [${parts[id].pivot.join(", ")}], attachedTo: ${parts[id].attachedTo ? `"${parts[id].attachedTo}"` : "null"}, note: ${JSON.stringify(parts[id].note)} },`).join("\n")}
};

/** The rig, in painting order. */
export const dragonRig: readonly DragonGroup[] = [
${expanded.map((n) => emit(n, 1)).join("\n")}
];

const isGroup = (n: DragonFacet | DragonGroup): n is DragonGroup => !Array.isArray(n);
const flatten = (nodes: readonly (DragonFacet | DragonGroup)[]): DragonFacet[] =>
  nodes.flatMap((n) => (isGroup(n) ? flatten(n.children) : [n]));

/** Every facet in painting order: the original flat list, kept for compatibility. */
export const dragonPolygons: readonly DragonFacet[] = flatten(dragonRig);
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error("dragon-art.ts is out of date: run node scripts/dragon/build-dragon-art.mjs");
    process.exit(1);
  }
  console.log("dragon-art.ts is up to date");
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${target}: ${polygons.length} facets in ${partIds.length} parts`);
}
